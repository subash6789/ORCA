# =========================================================
# GIS AGENT
# =========================================================

def gis_agent(
    state="Tamil Nadu",
    district=None
):

    # -----------------------------------------------------
    # CHECK STATE
    # -----------------------------------------------------

    if state not in STATE_MARINE_REGIONS:

        return {
            "agent": "GIS Agent",
            "status": "UNAVAILABLE",
            "data_status": "UNAVAILABLE",
            "state": state,
            "district": district,
            "message":
                "GIS region is not configured."
        }


    # -----------------------------------------------------
    # MARINE REGION
    # -----------------------------------------------------

    marine_region = STATE_MARINE_REGIONS[state]


    # -----------------------------------------------------
    # DISTRICT-LEVEL LOCATION
    # -----------------------------------------------------

    district_match = None
    if district and state in DISTRICT_COORDINATES:
        if district in DISTRICT_COORDINATES[state]:
            district_match = DISTRICT_COORDINATES[state][district]
        else:
            for d_name, d_val in DISTRICT_COORDINATES[state].items():
                if d_name.lower() == district.lower():
                    district_match = d_val
                    break

    if district_match:

        data = district_match

        location = district

        latitude = data["latitude"]

        longitude = data["longitude"]

        data_scope = "DISTRICT"


    # -----------------------------------------------------
    # STATE DEFAULT LOCATION
    # -----------------------------------------------------

    else:

        data = STATE_DEFAULTS[state]

        location = data["location"]

        latitude = data["latitude"]

        longitude = data["longitude"]

        data_scope = "STATE"


    # -----------------------------------------------------
    # RESPONSE
    # -----------------------------------------------------

    return {

        "agent":
            "GIS Agent",

        "status":
            "SUCCESS",

        "data_status":
            "MAPPED",

        "data_scope":
            data_scope,

        "state":
            state,

        "district":
            district if district else None,

        "location":
            location,

        "latitude":
            latitude,

        "longitude":
            longitude,

        "marine_region":
            marine_region,

        "country":
            "India",

        "source":
            "ORCA GIS Agent",

        "message":
            (
                "GIS location and marine-region mapping "
                "is available for the selected "
                "state and district."
            )
    }


